import { z } from 'zod';
import { LIMITS, id, kopecks, text, version } from './primitives';
import { PaymentMethod } from './enums';

/** Equal split into N parts, or one part per guest. */
export const SplitBody = z.discriminatedUnion('mode', [
  z
    .object({ mode: z.literal('equal'), parts: z.number().int().min(2).max(LIMITS.maxSplitParts) })
    .strict(),
  z.object({ mode: z.literal('guests') }).strict(),
]);
export type SplitBody = z.infer<typeof SplitBody>;

export const SplitPart = z.object({
  index: z.number().int().min(1),
  /** Guest number for `guests` mode, null for `equal`. */
  guest: z.number().int().nullable(),
  subtotal: kopecks,
  serviceFee: kopecks,
  total: kopecks,
});
export type SplitPart = z.infer<typeof SplitPart>;

export const SplitResult = z.object({
  mode: z.enum(['equal', 'guests']),
  total: kopecks,
  parts: z.array(SplitPart),
});
export type SplitResult = z.infer<typeof SplitResult>;

/**
 * `id` is generated by the client (UUID) and makes the request idempotent.
 * `amount` is what is applied to the bill; for cash `tendered` is what the guest handed over
 * (change = tendered - amount). Cards have no `tendered`.
 */
export const PaymentBody = z
  .object({
    id,
    method: PaymentMethod,
    amount: kopecks.min(1),
    tendered: kopecks.optional(),
    label: text(40).optional(),
    expectedVersion: version,
  })
  .strict()
  .superRefine((p, ctx) => {
    if (p.method === 'cash') {
      if (p.tendered === undefined) {
        ctx.addIssue({ code: 'custom', path: ['tendered'], message: 'Cash requires tendered' });
      } else if (p.tendered < p.amount) {
        ctx.addIssue({
          code: 'custom',
          path: ['tendered'],
          message: 'Tendered must cover the amount',
        });
      }
    } else if (p.tendered !== undefined) {
      ctx.addIssue({
        code: 'custom',
        path: ['tendered'],
        message: 'Card payments have no tendered amount',
      });
    }
  });
export type PaymentBody = z.infer<typeof PaymentBody>;
